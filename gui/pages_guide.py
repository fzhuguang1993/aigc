TITLES = [t for t, _ in CHAPTERS]
BODIES = dict(CHAPTERS)


class GuidePage(QWidget):
    def __init__(self, parent=None):
        super().__init__(parent)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(24, 12, 24, 12)
        lay.setSpacing(8)
        lay.addWidget(page_header("新手入门", "零基础看图学会全部功能", icon="📖"))

        body = QHBoxLayout()
        body.setSpacing(12)
        self.nav = QListWidget()
        self.nav.addItems(TITLES)
        self.nav.setFixedWidth(190)
        self.nav.currentRowChanged.connect(self._show)
        body.addWidget(self.nav)

        self.view = QTextBrowser()
        self.view.setOpenExternalLinks(True)
        self.view.setStyleSheet("QTextBrowser { background:#FFFFFF; border:1px solid #E5E7EB;"
                                " border-radius:10px; }")
        body.addWidget(self.view, 1)
        lay.addLayout(body, 1)
        self.nav.setCurrentRow(0)

    def _show(self, i):
        html = (BODIES.get(TITLES[i], "")
                .replace("<div_class_tip>", TIP_OPEN)
                .replace("<div_class_warn>", WARN_OPEN)
                .replace("</div_class_tip_end>", TIP_CLOSE))
        self.view.setHtml(html)

    def refresh(self):
        pass
